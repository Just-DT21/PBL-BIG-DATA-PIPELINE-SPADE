"""Private, per-user file storage with path-traversal containment.

Rules enforced here
-------------------
* Stored file names are generated from random identifiers, never from user
  input, so a hostile name cannot influence a path.
* Every path is resolved and asserted to live inside the owning user's
  directory before any read or write.
* The original file name is kept only as a metadata string for display and is
  sanitised before it is used in a ``Content-Disposition`` header.
* Files stream to disk in bounded chunks so a huge upload cannot exhaust RAM,
  and the byte counter aborts the transfer as soon as the limit is passed.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from . import config, db

_UNSAFE_NAME = re.compile(r"[^A-Za-z0-9._ \-()]+")
_CHUNK = 1024 * 1024


class StorageError(Exception):
    """Raised for any storage-level failure. Never includes file contents."""


class UploadTooLarge(StorageError):
    pass


def user_root(user_id: str) -> Path:
    # user_id is generated by us as "usr_<hex>"; re-validate defensively.
    if not re.fullmatch(r"usr_[0-9a-f]{32}", user_id or ""):
        raise StorageError("invalid user id")
    path = (config.USERS_DIR / user_id).resolve()
    _assert_within(path, config.USERS_DIR)
    return path


def file_dir(user_id: str) -> Path:
    return _ensure(user_root(user_id) / "files")


#: Worker scratch directories. A NAMI benchmark keeps its worker payload and result
#: beside its job scratch rather than in a second row in the jobs table, so both id
#: shapes are accepted here.
_JOB_ID = re.compile(r"(?:job|bmk)_[0-9a-f]{32}")


def job_dir(user_id: str, job_id: str) -> Path:
    if not _JOB_ID.fullmatch(job_id or ""):
        raise StorageError("invalid job id")
    return _ensure(user_root(user_id) / "jobs" / job_id)


def job_output_dir(user_id: str, job_id: str) -> Path:
    return _ensure(job_dir(user_id, job_id) / "output")


def benchmark_dir(user_id: str, benchmark_id: str) -> Path:
    """Private directory for one NAMI benchmark, validated like a job directory."""
    if not re.fullmatch(r"bmk_[0-9a-f]{32}", benchmark_id or ""):
        raise StorageError("invalid benchmark id")
    return _ensure(user_root(user_id) / "benchmarks" / benchmark_id)


def benchmark_output_dir(user_id: str, benchmark_id: str) -> Path:
    return _ensure(benchmark_dir(user_id, benchmark_id) / "output")


def purge_benchmark(user_id: str, benchmark_id: str) -> None:
    """Remove a benchmark's outputs and its worker scratch directory."""
    for root in (
        user_root(user_id) / "benchmarks" / benchmark_id,
        user_root(user_id) / "jobs" / benchmark_id,
    ):
        if root.exists():
            delete_path(root)


def _ensure(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    _assert_within(path, config.USERS_DIR)
    return path


def _assert_within(path: Path, root: Path) -> None:
    try:
        resolved = path.resolve()
    except OSError as exc:  # pragma: no cover - filesystem dependent
        raise StorageError("unresolvable path") from exc
    root = root.resolve()
    if resolved != root and root not in resolved.parents:
        raise StorageError("path escapes the storage root")


def safe_display_name(name: str, fallback: str = "upload") -> str:
    """Produce a header-safe file name that cannot carry a path separator."""
    base = os.path.basename((name or "").replace("\\", "/")).strip()
    base = _UNSAFE_NAME.sub("_", base).strip(". ")
    if not base:
        base = fallback
    return base[:180]


def resolve_owned(stored_path: str, user_id: str) -> Path:
    """Resolve a stored path and prove it belongs to ``user_id``."""
    root = user_root(user_id)
    path = Path(stored_path)
    if not path.is_absolute():
        path = (config.PROJECT_ROOT / path).resolve()
    _assert_within(path, root)
    if not path.is_file():
        raise StorageError("file is missing from storage")
    return path


@dataclass
class StoredUpload:
    path: Path
    size_bytes: int
    sha256: str


def save_upload(user_id: str, file_id: str, ext: str, stream, max_bytes: int) -> StoredUpload:
    """Persist an upload stream to the user's private directory.

    ``stream`` is any object exposing ``read(n)``. On any failure or oversize
    abort the partial file is removed.
    """
    directory = file_dir(user_id)
    clean_ext = re.sub(r"[^a-z0-9]", "", (ext or "").lower())[:8]
    suffix = f".{clean_ext}" if clean_ext else ".bin"
    target = (directory / f"{file_id}{suffix}").resolve()
    _assert_within(target, config.USERS_DIR)

    digest = hashlib.sha256()
    size = 0
    try:
        with open(target, "wb") as handle:
            while True:
                chunk = stream.read(_CHUNK)
                if not chunk:
                    break
                size += len(chunk)
                if size > max_bytes:
                    raise UploadTooLarge(
                        f"File exceeds the configured limit of {max_bytes} bytes."
                    )
                digest.update(chunk)
                handle.write(chunk)
        if size == 0:
            raise StorageError("The uploaded file is empty.")
    except BaseException:
        target.unlink(missing_ok=True)
        raise
    return StoredUpload(path=target, size_bytes=size, sha256=digest.hexdigest())


def write_bytes(user_id: str, job_id: str, filename: str, data: bytes) -> Path:
    """Write generated output inside an owned job directory."""
    target = (job_output_dir(user_id, job_id) / safe_display_name(filename)).resolve()
    _assert_within(target, config.USERS_DIR)
    target.write_bytes(data)
    return target


def stage_input(user_id: str, job_id: str, source: Path) -> Path:
    """Copy an owned upload into the job sandbox so workers read only job data."""
    target = (job_dir(user_id, job_id) / f"input{source.suffix}").resolve()
    _assert_within(target, config.USERS_DIR)
    shutil.copyfile(source, target)
    return target


def delete_path(path: Path) -> None:
    """Delete a file or directory tree that lives inside the storage root."""
    _assert_within(path, config.USERS_DIR)
    try:
        if path.is_dir():
            shutil.rmtree(path, ignore_errors=True)
        else:
            path.unlink(missing_ok=True)
    except OSError as exc:  # pragma: no cover
        raise StorageError("unable to delete stored data") from exc


def purge_job(user_id: str, job_id: str) -> None:
    root = user_root(user_id) / "jobs" / job_id
    if root.exists():
        delete_path(root)


def disk_usage(user_id: str) -> int:
    total = 0
    root = user_root(user_id)
    if not root.exists():
        return 0
    for dirpath, _dirnames, filenames in os.walk(root):
        for name in filenames:
            try:
                total += os.path.getsize(os.path.join(dirpath, name))
            except OSError:  # pragma: no cover
                continue
    return total
